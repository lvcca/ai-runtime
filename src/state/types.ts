import type { ValidatorResponse } from '../prompts/types/TaskValidator.js';

export type PromptChain = {
	userRequestChain?: string[];
	llmResponseChain?: string[];
};

export const Status = {
	FAILED: 'FAILED',
	QUEUED: 'QUEUED',
	RUNNING: 'RUNNING',
	COMPLETED: 'COMPLETED',
	HALTED: 'HALTED',
} as const;

export type _Status = (typeof Status)[keyof typeof Status];

export type Status = {
	status: _Status;
	message?: string;
};

export const TaskType = {
	TASK_DIRECT: 'TASK_DIRECT', // for direct llm query, no fancy tool or runtime stuffs
	TASK: 'TASK',
	EXECUTION: 'EXECUTION',
	JOB: 'JOB',
	SHELL_JOB: 'SHELL_JOB',
} as const;

export type TaskType = (typeof TaskType)[keyof typeof TaskType];

export type RelatedTransactionsChain =
	| {
			job?: string[];
			task?: string[];
			exec?: string[];
			shellJob?: string[];
	  }
	| undefined;

export type TransactionBase = {
	id: string;
}


/**
 * Represents a state transaction, extending the base transaction with
 * task-specific metadata, execution state, and result information.
 *
 * A state transaction can track the type and status of a task, maintain
 * its prompt chain and relationships to other transactions, and store
 * the final result and validator feedback.
 */
export type StateTransaction = TransactionBase & {
	/** The type of task associated with this transaction. */
	type?: TaskType;

	/** The current execution status of the transaction. */
	status?: Status;

	/** The sequence of prompts associated with this transaction. */
	promptChain?: PromptChain;

	/**
	 * References to related transactions, represented by their IDs.
	 * Related transactions are resolved when accessed rather than stored
	 * as fully populated objects.
	 */
	related?: RelatedTransactionsChain;

	/** The final response generated by an LLM for this transaction. */
	result?: string;

	/** The response returned by the validator after evaluating the result. */
	validatorResponse?: ValidatorResponse;
};
